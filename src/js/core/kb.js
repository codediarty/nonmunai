export function findConstruct(text) {
  if (!text) return null;
  const t = String(text).replace(/\s+/g, '').toLowerCase();
  let best = null;
  for (const c of CONSTRUCTS) {
    for (const n of c.names) {
      const nn = n.replace(/\s+/g, '').toLowerCase();
      if (t.includes(nn) && (!best || nn.length > best.len)) best = { c, len: nn.length };
    }
  }
  return best ? best.c : null;
}

export function isPopulation(word) {
  if (!word) return false;
  const w = String(word).trim();
  if (POPULATIONS.some((p) => w === p || w.endsWith(' ' + p) || w.endsWith(p))) return true;
  if (w.length <= 12 && POP_SUFFIX.test(w) && !findConstruct(w)) return true;
  return false;
}

export function guessField(text) {
  if (!text) return null;
  const t = String(text);
  for (const f of FIELDS) if (f.match.some((m) => t.includes(m))) return f;
  return null;
}

export function fieldById(id) {
  return FIELDS.find((f) => f.id === id) || FIELDS[FIELDS.length - 1];
}

export function typeById(id) {
  return PAPER_TYPES.find((t) => t.id === id) || PAPER_TYPES[0];
}
